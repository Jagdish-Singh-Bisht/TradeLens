
import './Strategies.css'
import { useEffect, useState } from 'react'
import {
    ResponsiveContainer,
    BarChart,
    Bar,
    XAxis,
    YAxis,
    CartesianGrid,
    Tooltip
} from 'recharts'

function Strategies() {
    const [strategies, setStrategies] = useState(null)
    const [error, setError] = useState('')

    useEffect(() => {
        fetch('http://localhost:8080/api/analytics/strategies/1', {
            credentials: 'include'
        })
            .then(response => {
                if (!response.ok) {
                    throw new Error('Failed to load strategy analytics.')
                }
                return response.json()
            })
            .then(data => setStrategies(data))
            .catch(error => {
                console.error('Error loading strategies:', error)
                setError(error.message)
            })
    }, [])

    if (error) {
        return (
            <main className="strategies">
                <h2>Strategy Performance</h2>
                <p>{error}</p>
            </main>
        )
    }

    if (!strategies) {
        return (
            <main className="strategies">
                <h2>Strategy Performance</h2>
                <p>Loading strategies...</p>
            </main>
        )
    }

    const chartData = strategies.map(item => ({
        strategy: item.strategy,
        totalProfitLoss: Number(item.analytics.totalProfitLoss ?? 0)
    }))

    return (
        <main className="strategies">
            <div className="strategy-heading">
                <h2>Strategy Performance</h2>
                <p>Compare performance across your trading strategies.</p>
            </div>

            <div className="strategy-table-container">
                <table className="strategy-table">
                    <thead>
                    <tr>
                        <th>Strategy</th>
                        <th>Total Trades</th>
                        <th>Win Rate</th>
                        <th>Total P&amp;L</th>
                        <th>Profit Factor</th>
                    </tr>
                    </thead>

                    <tbody>
                    {strategies.map(item => (
                        <tr key={item.strategy}>
                            <td>{item.strategy}</td>
                            <td>{item.analytics.totalTrades}</td>
                            <td>{item.analytics.winRate}%</td>
                            <td>₹{item.analytics.totalProfitLoss}</td>
                            <td>{item.analytics.profitFactor}</td>
                        </tr>
                    ))}
                    </tbody>
                </table>
            </div>

            <section className="strategy-chart-container">
                <h3>Profit &amp; Loss by Strategy</h3>
                <p>Compare the total P&amp;L generated by each strategy.</p>

                {chartData.length === 0 ? (
                    <p>No strategy data available yet.</p>
                ) : (
                    <ResponsiveContainer width="100%" height={320}>
                        <BarChart
                            data={chartData}
                            margin={{
                                top: 16,
                                right: 24,
                                left: 12,
                                bottom: 8
                            }}
                        >
                            <CartesianGrid strokeDasharray="3 3" />
                            <XAxis dataKey="strategy" />
                            <YAxis domain={[0, 'auto']} />
                            <Tooltip
                                formatter={value => [
                                    `₹${Number(value).toLocaleString('en-IN')}`,
                                    'Total P&L'
                                ]}
                            />
                            <Bar
                                dataKey="totalProfitLoss"
                                fill="#2563eb"
                                radius={[5, 5, 0, 0]}
                            />
                        </BarChart>
                    </ResponsiveContainer>
                )}
            </section>
        </main>
    )
}

export default Strategies
